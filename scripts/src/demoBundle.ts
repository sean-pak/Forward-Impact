// pnpm demo:bundle [dir]   writes the seed the Worker's POST /api/demo/reset restores (default: fixtures/seed).
// After Muse's output arrives: pnpm demo:bundle ./synthetic, then deploy the Worker. The Worker has no file access,
// so the CSV text travels inside the bundle. Validates the whole dataset first (needs the vault keys, as db:reset does).
import { writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { loadDataset, readSeedFiles } from "./dataset";
import { loadScriptKeys, root } from "./keys";

const dir = resolve(process.env.INIT_CWD ?? process.cwd(), process.argv.slice(2).filter((a) => a !== "--")[0] ?? join(root, "fixtures/seed"));
const files = readSeedFiles(dir);
const data = await loadDataset(dir, await loadScriptKeys());
const bytes = Object.values(files).reduce((n, t) => n + t.length, 0);
if (bytes > 4_000_000) {
  console.error(`The seed is ${(bytes / 1e6).toFixed(1)} MB of CSV. That is too large to bundle into the Worker; trim it or load it with pnpm seed:muse.`);
  process.exit(1);
}
const out = join(root, "apps/worker/src/vault/demoBundle.generated.ts");
writeFileSync(
  out,
  `// Generated by pnpm demo:bundle from ${dir.replace(root + "/", "")}. Do not edit by hand.\n` +
    `// Synthetic data only: the seed loader refuses CDCR numbers that are not SYN + 5 digits.\n` +
    `export const DEMO_FILES: Record<string, string> = ${JSON.stringify(files, null, 1)};\n`,
);
console.log(`Wrote ${out}\n${JSON.stringify(data.counts)}`);
